ALLOWED_CONTENT_TYPES = {
    "application/pdf",
    "application/x-pdf",
    "application/octet-stream",
    "binary/octet-stream",
    "application/vnd.pdf",
}


def _validate_pdf(file: UploadFile):
    """Validate uploaded file is a PDF by extension and magic header bytes."""
    if not file.filename.lower().endswith(".pdf"):
        raise HTTPException(status_code=400, detail="Only PDF files (.pdf) are accepted.")
    if file.content_type and file.content_type.lower() not in ALLOWED_CONTENT_TYPES:
        raise HTTPException(
            status_code=400,
            detail=f"Invalid content type: '{file.content_type}'. Expected PDF document.",
        )


# In-memory mapping of session_token -> temp_file_path to avoid leaking server filesystem paths
_IMPORT_SESSIONS: dict[str, str] = {}


@router.post("/import/preview", response_model=dict)
async def preview_import(
    db: Annotated[AsyncSession, Depends(get_db)],
    current_user: Annotated[object, Depends(require_roles(UserRole.SUPER_ADMIN, UserRole.HR_ADMIN))],
    file: UploadFile = File(...),
):
    """
    Upload an eSSL attendance PDF and return a preview of what will be imported.
    Does NOT save anything to the database.
    """
    _validate_pdf(file)

    # Check file size and magic bytes
    content = await file.read()
    if len(content) > settings.max_upload_size_bytes:
        raise HTTPException(
            status_code=400,
            detail=f"File too large. Maximum size is {settings.MAX_UPLOAD_SIZE_MB}MB.",
        )

    if not content.startswith(b"%PDF"):
        raise HTTPException(
            status_code=400,
            detail="The uploaded file does not appear to be a valid PDF document (missing %PDF header).",
        )

    # Save to temporary location for parsing
    upload_dir = os.path.join(settings.UPLOAD_DIR, "pdfs")
    os.makedirs(upload_dir, exist_ok=True)

    session_token = uuid.uuid4().hex
    safe_filename = file.filename.replace(" ", "_").replace("/", "_")
    temp_path = os.path.join(upload_dir, f"preview_{session_token}_{safe_filename}")

    with open(temp_path, "wb") as f:
        f.write(content)

    try:
        service = AttendanceImportService(db, current_user.id)
        preview = await service.preview(temp_path, file.filename, len(content))
        
        # Store session mapping internally and return opaque token
        _IMPORT_SESSIONS[session_token] = temp_path
        preview["session_token"] = session_token
        preview.pop("_temp_path", None)
        preview.pop("pdf_path", None)
        return preview
    except FileNotFoundError as e:
        raise HTTPException(status_code=400, detail=str(e))
    except Exception as e:
        if os.path.exists(temp_path):
            os.remove(temp_path)
        raise HTTPException(
            status_code=422,
            detail=f"Unable to process the attendance PDF. Please ensure it was generated by the eSSL attendance system. Error: {str(e)}",
        )


@router.post("/import/commit", response_model=dict)
async def commit_import(
    data: dict,
    db: Annotated[AsyncSession, Depends(get_db)],
    current_user: Annotated[object, Depends(require_roles(UserRole.SUPER_ADMIN, UserRole.HR_ADMIN))],
):
    """
    Commit a previewed import to the database using session_token.
    """
    session_token = data.get("session_token")
    temp_path = _IMPORT_SESSIONS.get(session_token) if session_token else data.get("_temp_path")

    if not temp_path or not os.path.exists(temp_path):
        raise HTTPException(status_code=400, detail="Invalid or expired import session. Please upload the file again.")

    data["_temp_path"] = temp_path

    service = AttendanceImportService(db, current_user.id)
    result = await service.commit(
        preview_data=data,
        duplicate_action=data.get("duplicate_action", "skip"),
        employee_mappings=data.get("employee_mappings", {}),
        department_mappings=data.get("department_mappings", {}),
    )

    # Cleanup session
    if session_token in _IMPORT_SESSIONS:
        del _IMPORT_SESSIONS[session_token]

    return result


