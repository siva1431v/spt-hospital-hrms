async def _resolve_single_approved_exception(db: AsyncSession, exc: AttendanceException, user_id: int):
    """When an exception (especially NO_OUT_PUNCH) is APPROVED, resolve the underlying Attendance row."""
    from datetime import timedelta, datetime, time
    from app.models.attendance import AttendanceCorrection, MonthlyAttendanceAggregate
    from app.models.shift import Shift
    from app.models.employee import Employee
    from sqlalchemy.orm import selectinload

    att = None
    if exc.attendance_id:
        res = await db.execute(
            select(Attendance)
            .options(selectinload(Attendance.employee).selectinload(Employee.shift))
            .where(Attendance.id == exc.attendance_id)
        )
        att = res.scalar_one_or_none()

    if not att and exc.employee_id and exc.exception_date:
        res = await db.execute(
            select(Attendance)
            .options(selectinload(Attendance.employee).selectinload(Employee.shift))
            .where(
                Attendance.employee_id == exc.employee_id,
                Attendance.attendance_date == exc.exception_date,
            )
        )
        att = res.scalar_one_or_none()

    if not att:
        return

    # Check if attendance is missing out-punch or incomplete or marked as exception
    if att.check_out_datetime is None or att.status == AttendanceStatus.PRESENT_INCOMPLETE or exc.exception_type == "NO_OUT_PUNCH" or not att.is_corrected:
        shift = None
        target_win = None
        if att.source_shift_code:
            from app.models.shift import ShiftCodeAlias
            alias_res = await db.execute(
                select(ShiftCodeAlias).options(selectinload(ShiftCodeAlias.shift)).where(
                    ShiftCodeAlias.device_code == att.source_shift_code.upper().strip()
                )
            )
            alias_obj = alias_res.scalar_one_or_none()
            if alias_obj:
                shift = alias_obj.shift
                target_win = alias_obj.target_window

        if not shift and att.employee and att.employee.shift:
            shift = att.employee.shift

        if not shift:
            # Fallback default shift GS
            s_res = await db.execute(select(Shift).where(Shift.code == "GS"))
            shift = s_res.scalar_one_or_none()

        shift_start = shift.start_time if shift else time(9, 30)
        shift_end = shift.end_time if shift else time(20, 0)
        is_overnight = shift.is_overnight if shift else False

        in_dt = att.check_in_datetime
        if not in_dt:
            if att.source_in_time and ":" in att.source_in_time:
                try:
                    ih, im = map(int, att.source_in_time.split(":"))
                    in_dt = datetime.combine(att.attendance_date, time(ih, im))
                except Exception:
                    in_dt = datetime.combine(att.attendance_date, shift_start)
            else:
                in_dt = datetime.combine(att.attendance_date, shift_start)

        in_mins = in_dt.hour * 60 + in_dt.minute

        def minute_distance(m1: int, m2: int) -> int:
            d = abs(m1 - m2)
            return min(d, 1440 - d)

        # For split shifts, match target_window or closest window
        if shift and shift.is_split and shift.start_time_2 and shift.end_time_2:
            if target_win == 2:
                shift_start = shift.start_time_2
                shift_end = shift.end_time_2
                is_overnight = shift.is_overnight_2
            elif target_win == 1:
                shift_start = shift.start_time
                shift_end = shift.end_time
                is_overnight = shift.is_overnight
            else:
                w1_start_mins = shift.start_time.hour * 60 + shift.start_time.minute
                w2_start_mins = shift.start_time_2.hour * 60 + shift.start_time_2.minute
                diff1 = minute_distance(in_mins, w1_start_mins)
                diff2 = minute_distance(in_mins, w2_start_mins)

                if diff2 < diff1:
                    shift_start = shift.start_time_2
                    shift_end = shift.end_time_2
                    is_overnight = shift.is_overnight_2
                else:
                    shift_start = shift.start_time
                    shift_end = shift.end_time
                    is_overnight = shift.is_overnight

        if is_overnight or (shift_end < shift_start):
            out_dt = datetime.combine(att.attendance_date + timedelta(days=1), shift_end)
        else:
            out_dt = datetime.combine(att.attendance_date, shift_end)

        dur_mins = max(0, int((out_dt - in_dt).total_seconds() / 60))
        if dur_mins < 60:
            raise HTTPException(
                status_code=400,
                detail=f"Cannot approve exception #{exc.id}: resulting duration is {dur_mins} minutes (< 1 hour). Please use manual HR correction to input valid punch times."
            )

        expected_mins = shift.expected_working_minutes if (shift and shift.expected_working_minutes) else dur_mins
        work_mins = min(dur_mins, expected_mins)
        ot_mins = max(0, dur_mins - expected_mins)

        orig_status = getattr(att.status, "value", str(att.status)) if att.status else "PRESENT_INCOMPLETE"
        new_status = AttendanceStatus.PRESENT_OVERNIGHT if (is_overnight or (shift_end < shift_start)) else AttendanceStatus.PRESENT

        att.check_in_datetime = in_dt
        att.check_out_datetime = out_dt
        att.source_out_time = shift_end.strftime("%H:%M")
        att.work_minutes = work_mins
        att.ot_minutes = ot_mins
        att.status = new_status
        att.is_corrected = True
        att.has_exception = False
        att.remarks = f"Exception #{exc.id} approved: out-punch credited to shift end {shift_end.strftime('%H:%M')}"

        # Record Correction log
        corr = AttendanceCorrection(
            attendance_id=att.id,
            corrected_by_id=user_id,
            original_check_in=in_dt,
            original_check_out=None,
            original_status=orig_status,
            corrected_check_in=in_dt,
            corrected_check_out=out_dt,
            corrected_status=new_status.value,
            reason=f"Exception #{exc.id} approved by HR: out-punch credited to shift end",
        )
        db.add(corr)


async def backfill_approved_exceptions(db: AsyncSession) -> int:
    """Backfill/resolve historically APPROVED exceptions whose Attendance records remain incomplete."""
    from app.models.attendance import ExceptionReviewStatus
    res = await db.execute(
        select(AttendanceException).where(
            AttendanceException.review_status.in_([
                ExceptionReviewStatus.APPROVED,
                ExceptionReviewStatus.APPROVED.value,
                "APPROVED",
            ])
        )
    )
    approved_excs = res.scalars().all()
    count = 0
    for exc in approved_excs:
        try:
            await _resolve_single_approved_exception(db, exc, user_id=1)
            count += 1
        except Exception:
            pass
    await db.flush()
    return count


