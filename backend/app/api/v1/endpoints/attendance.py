@router.put("/{attendance_id}/correct", response_model=dict)
async def correct_attendance(
    attendance_id: int,
    correction_data: dict,
    db: Annotated[AsyncSession, Depends(get_db)],
    current_user: Annotated[object, Depends(require_roles(UserRole.SUPER_ADMIN, UserRole.HR_ADMIN))],
):
    """Apply an HR correction to an attendance record. Preserves original values in audit trail."""
    from datetime import datetime, timezone

    result = await db.execute(
        select(Attendance)
        .where(Attendance.id == attendance_id)
        .options(selectinload(Attendance.corrections))
    )
    att = result.scalar_one_or_none()
    if not att:
        raise HTTPException(status_code=404, detail="Attendance record not found")

    reason = correction_data.get("reason", "").strip()
    if not reason:
        raise HTTPException(status_code=400, detail="A reason is required for attendance correction.")

    # Record the correction in audit trail
    correction = AttendanceCorrection(
        attendance_id=att.id,
        corrected_by_id=current_user.id,
        original_check_in=att.check_in_datetime,
        original_check_out=att.check_out_datetime,
        original_status=att.status.value,
        reason=reason,
    )

    # Apply corrections
    if correction_data.get("corrected_in_time"):
        try:
            h, m = map(int, correction_data["corrected_in_time"].split(":"))
            correction.corrected_check_in = datetime(
                att.attendance_date.year, att.attendance_date.month, att.attendance_date.day,
                h, m, tzinfo=timezone.utc
            )
            att.check_in_datetime = correction.corrected_check_in
        except ValueError:
            raise HTTPException(status_code=400, detail="Invalid corrected in time format. Use HH:MM.")

    if correction_data.get("corrected_out_time"):
        try:
            h, m = map(int, correction_data["corrected_out_time"].split(":"))
            correction.corrected_check_out = datetime(
                att.attendance_date.year, att.attendance_date.month, att.attendance_date.day,
                h, m, tzinfo=timezone.utc
            )
            att.check_out_datetime = correction.corrected_check_out
        except ValueError:
            raise HTTPException(status_code=400, detail="Invalid corrected out time format. Use HH:MM.")

    if correction_data.get("corrected_status"):
        try:
            new_status = AttendanceStatus(correction_data["corrected_status"])
            correction.corrected_status = new_status.value
            att.status = new_status
        except ValueError:
            raise HTTPException(status_code=400, detail=f"Invalid status value.")

    # Recalculate work_minutes if both times are now available
    if att.check_in_datetime and att.check_out_datetime:
        diff = att.check_out_datetime - att.check_in_datetime
        if diff.total_seconds() > 0:
            att.work_minutes = int(diff.total_seconds() / 60)

    att.is_corrected = True
    db.add(correction)

    await log_audit(
        db, current_user.id, "CORRECT", "Attendance", str(att.id),
        f"Corrected attendance for employee {att.employee_id} on {att.attendance_date}. Reason: {reason}",
        old_value=json.dumps({
            "check_in": str(correction.original_check_in),
            "check_out": str(correction.original_check_out),
            "status": correction.original_status,
        }),
        new_value=json.dumps({
            "check_in": str(att.check_in_datetime),
            "check_out": str(att.check_out_datetime),
            "status": att.status.value,
        }),
    )
    await db.commit()
    return {"message": "Attendance corrected successfully", "attendance_id": att.id}


@router.post("/reclassify-leave", response_model=dict)
async def reclassify_attendance_leave(
    data: AttendanceLeaveReclassifyRequest,
    db: Annotated[AsyncSession, Depends(get_db)],
    current_user: Annotated[object, Depends(require_roles(UserRole.SUPER_ADMIN, UserRole.HR_ADMIN))],
):
    """
    Reclassify a single day's attendance between ABSENT and LEAVE.
    Maintains audit trail and updates attendance record.
    """
    # 1. Locate record
    if data.attendance_id:
        res = await db.execute(select(Attendance).where(Attendance.id == data.attendance_id))
    elif data.employee_id and data.attendance_date:
        res = await db.execute(
            select(Attendance).where(
                Attendance.employee_id == data.employee_id,
                Attendance.attendance_date == data.attendance_date,
            )
        )
    else:
        raise HTTPException(status_code=400, detail="Must provide attendance_id or employee_id + attendance_date.")

    att = res.scalar_one_or_none()
    if not att:
        raise HTTPException(status_code=404, detail="Attendance record not found.")

    old_status = att.status
    if data.action == "MARK_LEAVE":
        new_status = AttendanceStatus.LEAVE
    elif data.action == "REVERT_ABSENT":
        new_status = AttendanceStatus.ABSENT
    else:
        raise HTTPException(status_code=400, detail="Action must be 'MARK_LEAVE' or 'REVERT_ABSENT'.")

    reason_str = data.reason.strip() if data.reason else f"Day reclassified from {old_status.value} to {new_status.value}"
    if data.leave_type_code:
        reason_str += f" ({data.leave_type_code})"

    correction = AttendanceCorrection(
        attendance_id=att.id,
        corrected_by_id=current_user.id,
        original_check_in=att.check_in_datetime,
        original_check_out=att.check_out_datetime,
        original_status=old_status.value,
        corrected_status=new_status.value,
        reason=reason_str,
    )
    db.add(correction)

    att.status = new_status
    att.is_corrected = True
    att.remarks = f"Leave Reclassified: {reason_str}"

    await log_audit(
        db, current_user.id, "RECLASSIFY_LEAVE", "Attendance", str(att.id),
        f"Reclassified employee {att.employee_id} on {att.attendance_date} to {new_status.value}. Reason: {reason_str}",
        old_value=json.dumps({"status": old_status.value}),
        new_value=json.dumps({"status": new_status.value}),
    )
    await db.commit()
    return {
        "message": f"Successfully reclassified attendance to {new_status.value}",
        "attendance_id": att.id,
        "new_status": new_status.value,
        "date": str(att.attendance_date),
    }


